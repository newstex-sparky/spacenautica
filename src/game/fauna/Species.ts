/**
 * Species catalogue. Every entry is pure data: a parametric body spec for
 * `BodyBuilder`, a shading recipe for `CreatureMaterial`, and behaviour numbers
 * for the boid / predator simulation. Adding a species is a data edit.
 *
 * The ids here must cover everything referenced by `world/terrain/Biomes.ts`.
 */
import * as THREE from 'three';
import type { TextureId } from '../assets/TextureIds';
import type { BodySpec, EyeSpec, FinSpec, LimbSpec } from './BodyBuilder';

export type Behaviour = 'school' | 'drifter' | 'predator';

/** Fragment-shader pattern generator selected per species. */
export const PAT_SCALES = 0;
export const PAT_STRIPES = 1;
export const PAT_SPOTS = 2;
export const PAT_LEATHER = 3;

export interface SpeciesDef {
  id: string;
  name: string;
  behaviour: Behaviour;
  /** Mean body length in metres; per-instance scale jitters around this. */
  length: number;
  sizeVar: number;
  skin: TextureId;
  /** Linear-space palette. */
  dorsal: THREE.Color;
  ventral: THREE.Color;
  finColor: THREE.Color;
  patternColor: THREE.Color;
  iris: THREE.Color;
  glowColor: THREE.Color;
  /** Emissive strength of the bioluminescent markings. */
  glow: number;
  /** Marking scale (higher = smaller patches) and pulse rate. */
  glowScale: number;
  glowRate: number;
  pattern: number;
  /** Pattern frequency (scale cells / stripe count) and contrast. */
  patternScale: number;
  patternFreq: number;
  patternContrast: number;
  roughness: number;
  roughnessVar: number;
  iridescence: number;
  /** Fin/membrane translucency, 0..1. */
  translucency: number;
  /** Whole-surface wing undulation (rays). */
  wing: boolean;
  /** Wavelengths of the travelling spine wave along the body. */
  waves: number;
  /** Counter-sway of the head, fraction of tail amplitude. */
  headSway: number;
  finFlap: number;
  wingWaves: number;
  limbFreq: number;
  idle: number;
  /** Tail-beat amplitude as a fraction of body length. */
  amp: number;
  /** Tail beats per second at cruise speed. */
  beat: number;
  cruise: number;
  burst: number;
  turnRate: number;
  /** Preferred metres above the sea floor. */
  altitude: [number, number];
  /** Preferred depth band (metres below sea level). */
  depth: [number, number];
  /** Boid tuning. */
  school: { radius: number; separation: number; align: number; cohere: number };
  /** Predator tuning. */
  senseRange: number;
  aggression: number;
  damage: number;
  /** Share of the fauna budget this species may claim. */
  budgetShare: number;
  /** Cast real shadows (large silhouettes only). */
  shadow: boolean;
  /** Emits gill bubbles. */
  bubbles: number;
  /** Picks up loose metal (stalkers). */
  scavenger: boolean;
  body: BodySpec;
}

const c = (hex: number) => new THREE.Color(hex).convertSRGBToLinear();

